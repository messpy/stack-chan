test('USB photo watchdog protects synchronous voice teardown before native camera start',()=>{
  const execute=archive.slice(archive.indexOf('  async function execute(request)'),archive.indexOf('  // Read-only status survives',archive.indexOf('  async function execute(request)')))
  const guard=execute.indexOf('photoRecoveryWatchdog(true)')
  const begin=execute.indexOf('beginCameraHandoff()')
  const release=execute.indexOf("markPhotoPhase('VOICE_RELEASE')")
  assert.ok(guard>=0 && begin>=0 && release>=0)
  assert.ok(guard < begin && begin < release,
    'photo watchdog must start before potentially blocking audio release')
  assert.match(execute,/photoGuardArmed&&!photoStarted/)
  assert.match(execute,/photoRecoveryWatchdog\(false\)/)
  assert.match(execute,/markPhotoPhase\('HANDOFF_BEGIN'\)/)
  const direct=readFileSync(new URL('../../host/app/archive-direct-chat.js',import.meta.url),'utf8')
  assert.match(direct,/photoRecoveryCheckpoint\(2\)/)
  assert.match(direct,/photoRecoveryCheckpoint\(4\);trace\('\[vision\] native voice close begin/)
  assert.match(direct,/photoRecoveryCheckpoint\(5\);trace\('\[vision\] native voice close done/)
  assert.match(direct,/photoRecoveryCheckpoint\(6\)/)
})
