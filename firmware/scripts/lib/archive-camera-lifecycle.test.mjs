import { test } from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'

const runtime = readFileSync(new URL('../../host/app/runtime-camera.ts', import.meta.url), 'utf8')
const archive = readFileSync(new URL('../../host/app/lan-archive.js', import.meta.url), 'utf8')

test('runtime camera holds touch/I2C paused from capture until native camera close', () => {
  const classStart = runtime.indexOf('export class StackchanRuntimeCamera')
  const captureStart = runtime.indexOf('  async capture(', classStart)
  const capture = runtime.slice(captureStart, runtime.indexOf('  #pauseTouchPanel()', captureStart))
  assert.ok(capture.startsWith('  async capture('))
  assert.match(capture, /this\.#cameraActive\s*=\s*true/)
  assert.match(capture, /catch\s*\(error\)/)
  assert.doesNotMatch(capture, /finally\s*\{\s*if\s*\(!wasActive\)\s*this\.#resumeTouchPanel\(\)/)

  const closeStart = runtime.indexOf('  close(): ', classStart)
  const close = runtime.slice(closeStart, captureStart)
  assert.match(close, /this\.#camera\.close\?\.\(\)/)
  assert.match(close, /this\.#resumeTouchPanel\(\)/)
  assert.match(close, /return result\.then\(\(\) => finish\(\), fail\)/)
})

test('photo processes JPEG/SD in runtime capture continuation before closing DMA frame',()=>{
  const photo = archive.slice(archive.indexOf('async function photo('), archive.indexOf('async function describeImage('))
  const processor=photo.slice(photo.indexOf('  const processFrame=captured=>'),photo.indexOf('  markPhotoPhase(\'CAMERA_START\')'))
  assert.match(photo, /robot\.camera\.captureWithProcessor\(/)
  assert.doesNotMatch(photo, /frame=await robot\.camera\.capture\(/)
  assert.match(processor, /markPhotoPhase\('CAMERA_CAPTURE'\)/)
  assert.match(processor, /markPhotoPhase\('JPEG_START'\)/)
  assert.match(processor, /markPhotoPhase\('JPEG_DONE'\)/)
  assert.match(processor, /markPhotoPhase\('SD_SAVE_START'\)/)
  assert.match(processor, /markPhotoPhase\('CAMERA_SAVE'\)/)
  assert.match(processor, /finally\{releaseCamera\(captured\);\}/)
  assert.doesNotMatch(processor, /\bawait\b/)
  const closed=photo.slice(photo.indexOf('  const releaseCamera=captured=>'),photo.indexOf('  const processFrame=captured=>'))
  assert.match(closed, /captured\?\.close\?\.\(\)/)
  assert.match(closed, /robot\.camera\.close\(\)/)
  assert.ok(closed.indexOf('captured?.close?.()')<closed.indexOf('robot.camera.close()'))
  assert.match(closed, /markPhotoPhase\('CAMERA_CLOSED'\)/)
  assert.ok(processor.indexOf('CAMERA_CAPTURE') < processor.indexOf('JPEG_START'))
  assert.ok(processor.indexOf('JPEG_START') < processor.indexOf('JPEG_DONE'))
  assert.ok(processor.indexOf('JPEG_DONE') < processor.indexOf('SD_SAVE_START'))
  assert.ok(processor.indexOf('SD_SAVE_START') < processor.indexOf('CAMERA_SAVE'))
})
test('runtime invokes processor in same capture continuation without another await',()=>{
  const fast=runtime.slice(runtime.indexOf('  async captureWithProcessor<'),runtime.indexOf('  #pauseTouchPanel()',runtime.indexOf('  async captureWithProcessor<')))
  assert.match(fast, /const frame = await this\.#camera\.capture\(options\)/)
  assert.match(fast, /return processor\(frame\)/)
  assert.match(fast, /this\.#cameraActive = true/)
  const afterFrame=fast.slice(fast.indexOf("traceMessage('[runtime-camera] processor enter"),fast.indexOf('return processor(frame)'))
  assert.doesNotMatch(afterFrame, /\bawait\b|\.then\(/)
})


test('photo recovery watchdog runs independently of JS during camera/JPEG/SD and is disarmed in finally',()=>{
  const native=readFileSync(new URL('../../host/app/archive-usb.c',import.meta.url),'utf8')
  const usb=readFileSync(new URL('../../host/app/archive-usb.js',import.meta.url),'utf8')
  const photo=archive.slice(archive.indexOf('async function photo('),archive.indexOf('async function describeImage('))
  assert.match(native, /#define SC_PHOTO_WATCHDOG_US 60000000LL/)
  assert.match(native, /esp_timer_start_once\(/)
  assert.match(native, /esp_restart\(\)/)
  assert.match(native, /RTC_NOINIT_ATTR/)
  assert.match(native, /sc_photo_recovery_cookie = SC_PHOTO_RECOVERY_MAGIC/)
  assert.match(native, /esp_reset_reason\(\) == ESP_RST_SW/)
  assert.match(usb, /photoRecoveryTriggered = native\('xs_archive_photo_watchdog_triggered'\)/)
  assert.match(archive, /usbOperation:\{active:false,phase:photoProgress,watchdogReset:photoRecoveryTriggered\(\),watchdogStage:photoRecoveryLastCheckpoint\(\),\.\.\.photoDiagnostic\(\)\}/)
  assert.match(usb, /photoRecoveryWatchdog = native\('xs_archive_photo_watchdog'\)/)
  assert.ok(photo.indexOf('photoRecoveryWatchdog(true)')>=0)
  assert.ok(photo.indexOf('photoRecoveryWatchdog(true)')<photo.indexOf('robot.camera.captureWithProcessor'))
  assert.ok(photo.indexOf('photoRecoveryWatchdog(false)')>photo.indexOf('robot.camera.captureWithProcessor'))
  assert.match(photo,/if\(cameraClosed\)\{[\s\S]*?photoRecoveryWatchdog\(false\)/)
})

