#!/usr/bin/env python3
"""Verify pinned official assets and generate 16-byte aligned flash constants."""
import hashlib
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
dst=ROOT/'vendor/koeact'
assets=[('koeact_model_data','ralomi_e13_stream40.espdl','dce593c8c9293c5565d1126e2f5b96a8e8151259044fc0d3c2f79a80d62eca92'),('koeact_weights_data','a2_weights.bin','61ee72e27af12907dd535908ee941b29fdee2bc3521e421705812adfa05ba4a6')]
with (dst/'koeact-assets.c').open('w') as out:
 out.write('// Generated by scripts/prepare-koeact-assets.py. KoeAct-JP, Apache-2.0.\n')
 for symbol,name,expected in assets:
  data=(dst/name).read_bytes()
  if hashlib.sha256(data).hexdigest()!=expected:raise SystemExit('Checksum mismatch: '+name)
  out.write('const unsigned char '+symbol+'[] __attribute__((aligned(16))) = {\n')
  for at in range(0,len(data),32):out.write(','.join('0x%02x'%b for b in data[at:at+32])+',\n')
  out.write('};\n')
print('Verified both pinned models; generated aligned flash assets')
